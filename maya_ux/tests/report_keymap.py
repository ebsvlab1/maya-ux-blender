"""Industry Compatible 대비 MayaUX 매핑 분석표를 Markdown 으로 출력 (Phase 0 산출물).

    python maya_ux/tests/report_keymap.py > out.md      # bpy 모듈 필요
"""

import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, REPO)

import bpy  # noqa: E402

from maya_ux.keymap import conflicts as C  # noqa: E402
from maya_ux.keymap import registry  # noqa: E402
from maya_ux.keymap.mappings import MAPPINGS, PROFILES, KeymapState  # noqa: E402


def main():
    bpy.ops.preferences.keyconfig_activate(filepath=bpy.utils.preset_find("Industry_Compatible", "keyconfig"))
    st = KeymapState()
    st.mapping_ids = [m.id for m in MAPPINGS]
    registry.apply(st, [], platform="linux")
    print(f"<!-- generated by tests/report_keymap.py on Blender {bpy.app.version_string} -->")
    print("| 항목 | 영역 | 키 | Maya | Blender 명령 | 프로파일 | 우선 | IC 대비 상태 | 비고 |")
    print("|---|---|---|---|---|---|---|---|---|")
    for m in MAPPINGS:
        a = registry.analyses[m.id]
        profiles = ", ".join(p for p in PROFILES if p in m.profiles) or "(옵션)"
        status = {C.BASELINE: "✅ IC 그대로", C.FREE: "➕ MayaUX 추가", C.CONFLICT: "⚠️ 충돌"}.get(a.status, a.label)
        notes = [f"충돌: {it.describe()}" for it in a.conflicts[:2]]
        if m.note:
            notes.append(m.note)
        props = ""
        if m.properties:
            props = " " + ", ".join(f"{k}={v}" for k, v in m.properties.items() if k != "cycle")
        print(f"| {m.label} | {m.context} | `{m.event.label()}` | {m.maya} | `{m.idname}`{props} | {profiles} | "
              f"{m.priority} | {status} | {'<br>'.join(notes)} |")
    registry.remove_all([])


if __name__ == "__main__":
    main()
